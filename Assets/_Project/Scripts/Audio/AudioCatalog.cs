using System;
using System.Collections.Generic;
using Skyrift.Core.Ids;
using Skyrift.Data;
using UnityEngine;

namespace Skyrift.Audio
{
    /// <summary>
    /// One authored sound cue (TECH_DOC §4.18 extension point). Adding a sound is a row here plus a clip —
    /// never a code change, and never a new AudioSource in a scene.
    /// </summary>
    [Serializable]
    public sealed class SfxDefinition
    {
        [Tooltip("Stable snake_case cue id referenced by gameplay and by ObstacleDefinition.impactSfxId.")]
        public string id;

        [Tooltip("Placeholder clips are generated by the editor setup tool and are labelled replaceable.")]
        public AudioClip clip;

        public AudioBus bus = AudioBus.Sfx;

        [Range(0f, 1f)] public float volume = 1f;
        [Range(0.1f, 3f)] public float pitch = 1f;

        [Tooltip("Random pitch spread applied per play, so repeated cues do not sound like a machine gun.")]
        [Range(0f, 0.5f)] public float pitchVariance = 0.04f;

        [Tooltip("Maximum simultaneous voices for this cue. The oldest is stolen when the cap is reached.")]
        [Min(1)] public int voiceCap = 3;

        [Tooltip("Minimum seconds between two plays of this cue. 0 = no cooldown.")]
        [Min(0f)] public float cooldown;

        public bool spatial;
        [Min(0.1f)] public float minDistance = 2f;
        [Min(0.1f)] public float maxDistance = 45f;
    }

    /// <summary>
    /// One music layer. Its weight is a function of intensity, so the number of stems is authored data:
    /// adding a fifth layer is a row, not a change to the mixer code (TECH_DOC §4.18).
    /// </summary>
    [Serializable]
    public sealed class MusicStem
    {
        public AudioClip clip;

        [Tooltip("Intensity at which this stem starts becoming audible.")]
        [Range(0f, 1f)] public float fadeInAt;

        [Tooltip("Intensity at which this stem reaches full weight. Equal to fadeInAt = always on.")]
        [Range(0f, 1f)] public float fullAt = 1f;

        [Range(0f, 1f)] public float volume = 1f;

        /// <summary>Authored weight curve, evaluated without allocation.</summary>
        public float WeightAt(float intensity)
        {
            if (fullAt <= fadeInAt) return intensity >= fullAt ? 1f : 0f;
            return Mathf.Clamp01((intensity - fadeInAt) / (fullAt - fadeInAt));
        }
    }

    /// <summary>A layered music track. All stems start together and stay sample-aligned while looping.</summary>
    [Serializable]
    public sealed class MusicTrack
    {
        [Tooltip("Stable snake_case id. WorldDefinition.musicId references this.")]
        public string id;

        public List<MusicStem> stems = new List<MusicStem>();

        [Range(0f, 1f)] public float volume = 1f;
        public bool loop = true;
    }

    /// <summary>
    /// The audio content catalog (TECH_DOC §4.18). Referenced directly by the composition root rather than
    /// living in <c>GameDatabase</c>, because clips and mixer routing are an Audio concern and Data must not
    /// depend on them. Indices are built once and rebuilt only when the asset changes in the editor.
    /// </summary>
    [CreateAssetMenu(fileName = "AudioCatalog", menuName = "Skyrift/Audio/Audio Catalog")]
    public sealed class AudioCatalog : ScriptableObject, IValidatable
    {
        public List<SfxDefinition> sfx = new List<SfxDefinition>();
        public List<MusicTrack> music = new List<MusicTrack>();

        private Dictionary<SfxId, SfxDefinition> _sfxIndex;
        private Dictionary<MusicId, MusicTrack> _musicIndex;

        public bool TryGetSfx(SfxId id, out SfxDefinition definition)
        {
            if (_sfxIndex == null) BuildIndex();
            return _sfxIndex.TryGetValue(id, out definition);
        }

        public bool TryGetMusic(MusicId id, out MusicTrack track)
        {
            if (_musicIndex == null) BuildIndex();
            return _musicIndex.TryGetValue(id, out track);
        }

        /// <summary>Drops the lazy indices. Called from OnValidate and by the editor setup tool after writing rows.</summary>
        public void InvalidateIndex()
        {
            _sfxIndex = null;
            _musicIndex = null;
        }

        public void Validate(ValidationReport report)
        {
            const string t = nameof(AudioCatalog);

            var seenSfx = new HashSet<string>(StringComparer.Ordinal);
            int sfxCount = sfx != null ? sfx.Count : 0;
            for (int i = 0; i < sfxCount; i++)
            {
                SfxDefinition def = sfx[i];
                if (def == null) { report.Error(t, "-", "sfx_null", $"sfx[{i}] is null."); continue; }

                if (!StableId.IsValidString(def.id))
                    report.Error(t, def.id, "sfx_id", $"sfx[{i}].id '{def.id}' is not a valid id.");
                else if (!seenSfx.Add(def.id))
                    report.Error(t, def.id, "sfx_id_unique", $"Duplicate sfx id '{def.id}'.");

                // A missing clip is a warning, not an error: the service degrades to silence and reports once,
                // so placeholder art can be swapped in without blocking a build.
                if (def.clip == null) report.Warn(t, def.id, "sfx_clip", "No clip assigned; the cue will be silent.");
                if (def.voiceCap < 1) report.Error(t, def.id, "voice_cap", "voiceCap must be >= 1.");
                if (def.maxDistance <= def.minDistance) report.Error(t, def.id, "distance", "maxDistance must exceed minDistance.");
            }

            var seenMusic = new HashSet<string>(StringComparer.Ordinal);
            int musicCount = music != null ? music.Count : 0;
            for (int i = 0; i < musicCount; i++)
            {
                MusicTrack track = music[i];
                if (track == null) { report.Error(t, "-", "music_null", $"music[{i}] is null."); continue; }

                if (!StableId.IsValidString(track.id))
                    report.Error(t, track.id, "music_id", $"music[{i}].id '{track.id}' is not a valid id.");
                else if (!seenMusic.Add(track.id))
                    report.Error(t, track.id, "music_id_unique", $"Duplicate music id '{track.id}'.");

                if (track.stems == null || track.stems.Count == 0)
                {
                    report.Error(t, track.id, "stems", "A music track needs at least one stem.");
                    continue;
                }

                bool anyClip = false;
                for (int s = 0; s < track.stems.Count; s++)
                {
                    MusicStem stem = track.stems[s];
                    if (stem == null) { report.Error(t, track.id, "stem_null", $"stems[{s}] is null."); continue; }
                    if (stem.clip != null) anyClip = true;
                    if (stem.fullAt < stem.fadeInAt)
                        report.Error(t, track.id, "stem_band", $"stems[{s}].fullAt must be >= fadeInAt.");
                }

                if (!anyClip) report.Warn(t, track.id, "stem_clips", "No stem has a clip; the track will be silent.");
            }
        }

        private void BuildIndex()
        {
            int sfxCount = sfx != null ? sfx.Count : 0;
            _sfxIndex = new Dictionary<SfxId, SfxDefinition>(sfxCount);
            for (int i = 0; i < sfxCount; i++)
            {
                SfxDefinition def = sfx[i];
                if (def == null || string.IsNullOrEmpty(def.id) || _sfxIndex.ContainsKey(def.id)) continue;
                _sfxIndex.Add(def.id, def);
            }

            int musicCount = music != null ? music.Count : 0;
            _musicIndex = new Dictionary<MusicId, MusicTrack>(musicCount);
            for (int i = 0; i < musicCount; i++)
            {
                MusicTrack track = music[i];
                if (track == null || string.IsNullOrEmpty(track.id) || _musicIndex.ContainsKey(track.id)) continue;
                _musicIndex.Add(track.id, track);
            }
        }

#if UNITY_EDITOR
        private void OnValidate() => InvalidateIndex();
#endif
    }
}